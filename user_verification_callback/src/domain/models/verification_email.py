from dataclasses import dataclass


@dataclass
class VerificationEmail:
    """Content of the identity verification result email.

    The mandatory content of the notification (team decision, documented
    in ``docs/rf007-sequence-view.md``) is the final status, the RUV
    generated by TrueNative, and the user data used in the verification
    process. The status and the RUV come from the user record persisted
    by the platform, and the profile fields are the same fields the
    platform sent to the identity provider.
    """

    user_id: str
    status: str
    ruv: str
    score: int | float
    username: str | None = None
    email: str | None = None
    dni: str | None = None
    full_name: str | None = None
    phone_number: str | None = None
