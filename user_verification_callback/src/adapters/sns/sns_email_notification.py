"""SNS adapter: the email notification of the verification result.

The notification mechanism is the SNS email topic provisioned for RF-007
by the ``4_sns`` Terraform stack (TASK-003). The deploy pipeline exports
the ``user_verification_topic_arn`` stack output as the
``USER_VERIFICATION_TOPIC_ARN`` environment variable for the envsubst
step that applies the Kubernetes manifests, so the topic ARN is provided
through the environment and no recipient address appears in this code:
the topic's email subscription delivers the message to the address
configured at deploy time.
"""

import logging

import boto3
from botocore.exceptions import ClientError

from config import Settings
from domain.models.verification_email import VerificationEmail
from domain.ports.email_notification_port import EmailNotificationPort
from errors import EmailNotificationError

logger = logging.getLogger("user_verification_callback")

VERIFIED_OUTCOME = "Your identity was successfully verified."
NOT_VERIFIED_OUTCOME = "Your identity could not be verified with the provided data."


def compose_verification_email(email: VerificationEmail) -> tuple[str, str]:
    """Build the subject and the body of the result email.

    The content is fixed by the acceptance criteria: the final status,
    the RUV generated by TrueNative, and the user data used in the
    verification process (the same fields the platform sent to the
    identity provider). Absent fields are shown as "Not provided".
    """
    subject = f"Identity verification result: {email.status}"
    outcome = VERIFIED_OUTCOME if email.status == "VERIFICADO" else NOT_VERIFIED_OUTCOME
    data_fields = (
        ("Email", email.email),
        ("DNI", email.dni),
        ("Full name", email.full_name),
        ("Phone number", email.phone_number),
    )
    data_lines = [
        f"  {label}: {value if value is not None else 'Not provided'}"
        for label, value in data_fields
    ]
    greeting = f"Hello {email.username}," if email.username else "Hello,"
    body = "\n".join(
        [
            greeting,
            "",
            "Your identity verification process has finished.",
            "",
            f"Final status: {email.status}",
            outcome,
            f"Verification record (RUV): {email.ruv}",
            f"Score: {email.score}",
            "",
            "User data used in the verification process:",
            *data_lines,
            "",
            "This notification was generated automatically by the platform "
            "after the verification result was received and stored. The "
            "final status, the verification record, and the data above "
            f"match the user record {email.user_id} in the platform.",
        ]
    )
    return subject, body


class SnsEmailNotification(EmailNotificationPort):
    """Publish the verification result email to the RF-007 SNS topic.

    When the topic ARN is empty (local runs without the AWS stack) the
    notification is skipped with a logged notice: the composed email is
    still logged so the content can be inspected during manual
    verification.
    """

    def __init__(
        self,
        client=None,
        topic_arn: str | None = None,
        region: str | None = None,
        endpoint_url: str | None = None,
    ):
        self._owns_client = client is None
        self._topic_arn = (
            topic_arn if topic_arn is not None else Settings.user_verification_topic_arn
        )
        self._client = client or boto3.client(
            "sns",
            region_name=region or Settings.aws_region,
            endpoint_url=endpoint_url or None,
        )

    def notify_verification_result(self, email: VerificationEmail) -> bool:
        subject, body = compose_verification_email(email)
        logger.info(
            "Email notification composed for user %s (status %s, RUV %s):\n"
            "Subject: %s\n%s",
            email.user_id,
            email.status,
            email.ruv,
            subject,
            body,
        )
        if not self._topic_arn:
            logger.warning(
                "Email notification for user %s skipped: the SNS topic ARN "
                "is not configured",
                email.user_id,
            )
            return False
        try:
            self._client.publish(
                TargetArn=self._topic_arn, Subject=subject, Message=body
            )
        except ClientError as exc:
            logger.error(
                "Email notification for user %s failed to publish to %s: %s",
                email.user_id,
                self._topic_arn,
                exc,
            )
            raise EmailNotificationError(
                "The SNS email topic could not receive the message"
            ) from exc
        return True

    def close(self) -> None:
        """Close the underlying SNS client when we own it."""
        if self._owns_client:
            self._client.close()
