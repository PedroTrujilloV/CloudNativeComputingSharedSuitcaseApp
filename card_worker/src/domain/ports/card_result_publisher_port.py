"""Port for publishing the card result email notification.

The email is the mandatory output of the asynchronous phase of the
RF-006 flow: every outcome (APROBADA, RECHAZADA, and the POR_VERIFICAR
fallback after the dead letter queue move) produces a notification with
the process result, the basic card data as stored in the database, and
the RUV generated by TrueNative. The worker publishes the message to the
SNS topic of the 4_sns stack; the topic's email protocol subscription
(delivery address read from the EMAIL_TO_NOTIFY key of the
secrets-pipeline-native-map secret) performs the actual delivery, so the
worker never handles SMTP or provider credentials.
"""

from abc import ABC, abstractmethod


class CardResultPublisherPort(ABC):
    """Driven interface for the card result email notification."""

    @abstractmethod
    def publish_card_result(
        self,
        card_id: str,
        status: str,
        ruv: str,
        last_four_digits: str,
        issuer: str,
        updated_at: str,
        owner_email: str,
    ) -> None:
        """Publish the email notification of the card verification result.

        The message carries only the stored card data (the id, the last
        four digits, the issuer, the status, and the dates) and the RUV:
        the raw card number and the CVV are never published.

        Implementations raise on a publish failure, so the queue redelivers
        the event and the notification is retried on the next invocation
        (the status update is idempotent by card id, so the retry is safe).
        The exception is the documented POR_VERIFICAR fallback, where the
        invocation fails anyway: the caller logs the failure instead of
        raising, because the event moves to the dead letter queue either
        way.

        A publisher without a configured topic skips the publish and logs
        it, so the worker can run before the serverless wiring of the
        notification is in place.
        """
