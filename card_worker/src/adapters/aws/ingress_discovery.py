"""Runtime discovery of the single external host of the platform.

When the worker runs on AWS Lambda it reaches TrueNative through the
classic load balancer that the EKS cloud controller manager creates for
the LoadBalancer service of the ingress-nginx controller. The name (and
therefore the DNS name) of that balancer is generated by the cluster, so
it is not known at deploy time: the 6_lambda Terraform stack cannot read
it as a data source (it only exists after the k8s deploy step), and it
cannot be committed to a manifest either. The worker therefore discovers
the host at runtime through the ELBv1 API, filtering the balancers of the
account by the standard kubernetes service name tag that the cloud
controller manager sets on every load balancer it creates.
"""

import boto3

from config import Settings
from errors import TrueNativePollingError

# Tag that the EKS cloud controller manager sets on the load balancer it
# creates for a LoadBalancer service.
KUBERNETES_SERVICE_NAME_TAG = "kubernetes.io/service-name"
INGRESS_SERVICE_NAME = "ingress-nginx/ingress-nginx-controller"


def discover_truenative_base_url(
    region: str | None = None, client_factory=None
) -> str:
    """Return the https base URL of the ingress load balancer.

    Raises ``TrueNativePollingError`` when the balancer cannot be found,
    so the failure is treated like any other polling failure: the
    invocation fails and the queue redelivers the event (the discovery is
    transient during a deployment, persistent on a misconfiguration).
    """
    if region is None:
        region = Settings.aws_region
    if client_factory is not None:
        client = client_factory(region)
    else:
        client = _default_client(region)

    descriptions = client.describe_load_balancers()["LoadBalancerDescriptions"]
    if not descriptions:
        raise TrueNativePollingError(
            "No classic load balancer was found in the account"
        )

    names = [description["LoadBalancerName"] for description in descriptions]
    tags_by_name = {
        chunk["LoadBalancerName"]: {
            tag["Key"]: tag["Value"] for tag in chunk.get("Tags", [])
        }
        for chunk in client.describe_tags(LoadBalancerNames=names)["TagDescriptions"]
    }

    for description in descriptions:
        tags = tags_by_name.get(description["LoadBalancerName"], {})
        if tags.get(KUBERNETES_SERVICE_NAME_TAG) == INGRESS_SERVICE_NAME:
            return f"https://{description['DNSName']}"

    raise TrueNativePollingError(
        "No classic load balancer is tagged as the ingress-nginx service "
        f"({INGRESS_SERVICE_NAME})"
    )


def _default_client(region: str):
    return boto3.client("elb", region_name=region)
