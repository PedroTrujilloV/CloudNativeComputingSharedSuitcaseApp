"""HTTP schemas of the credit cards application."""

import re

from pydantic import BaseModel, Field, field_validator

from domain.services.card_expiration import is_valid_expiration_format

_CARD_NUMBER_PATTERN = re.compile(r"^\d{13,19}$")
_CVV_PATTERN = re.compile(r"^\d{3,4}$")


class CreateCreditCardRequest(BaseModel):
    """Request body of ``POST /credit-cards``.

    The fields match the RF-006 API contract. The raw card number and the
    CVV are consumed by the TrueNative tokenization call and are never
    persisted by this application.
    """

    cardNumber: str = Field(
        min_length=1,
        max_length=19,
        description="Card number in digits only, 13 to 19 digits",
    )
    cvv: str = Field(min_length=1, max_length=4, description="Card security code")
    expirationDate: str = Field(
        min_length=5,
        max_length=7,
        description="Expiration year and month in the YY/MM format, for example 28/01",
    )
    cardHolderName: str = Field(
        min_length=1, max_length=100, description="Name of the card holder"
    )

    @field_validator("cardNumber")
    @classmethod
    def validate_card_number(cls, value: str) -> str:
        if not _CARD_NUMBER_PATTERN.match(value):
            raise ValueError(
                "cardNumber must contain only digits, from 13 to 19 digits"
            )
        return value

    @field_validator("cvv")
    @classmethod
    def validate_cvv(cls, value: str) -> str:
        if not _CVV_PATTERN.match(value):
            raise ValueError("cvv must contain 3 or 4 digits")
        return value

    @field_validator("expirationDate")
    @classmethod
    def validate_expiration_date(cls, value: str) -> str:
        if not is_valid_expiration_format(value):
            raise ValueError(
                "expirationDate must use the YY/MM format, for example 28/01"
            )
        return value

    @field_validator("cardHolderName")
    @classmethod
    def validate_card_holder_name(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("cardHolderName must not be empty")
        return value


class CreateCreditCardResponse(BaseModel):
    """Success response of ``POST /credit-cards`` (HTTP 201)."""

    id: str = Field(description="Card identifier in UUID format")
    userId: str = Field(description="Owner user identifier")
    createdAt: str = Field(
        description="Creation date in ISO yyyy-mm-ddTHH:MM:SS, UTC 0"
    )


class CreditCardResponse(BaseModel):
    """Card item of ``GET /credit-cards`` (HTTP 200).

    The item carries the stored card data exactly as persisted, including
    the payment ``token``: the API contract of the exercise documents the
    token in the listing even though a real service would never expose it.
    The raw card number and the CVV are not stored by this application, so
    they cannot appear here. The dates follow the entity contract (ISO
    yyyy-mm-ddTHH:MM:SS, UTC 0).
    """

    id: str = Field(description="Card identifier in UUID format")
    token: str = Field(description="Payment token generated by TrueNative")
    userId: str = Field(description="Owner user identifier")
    lastFourDigits: str = Field(description="Last four digits of the card number")
    issuer: str = Field(description="Card issuer (documented enum value)")
    status: str = Field(description="Card status (POR_VERIFICAR, RECHAZADA, APROBADA)")
    createdAt: str = Field(
        description="Creation date in ISO yyyy-mm-ddTHH:MM:SS, UTC 0"
    )
    updatedAt: str = Field(
        description="Last update date in ISO yyyy-mm-ddTHH:MM:SS, UTC 0"
    )


class CountCreditCardsResponse(BaseModel):
    """Success response of ``GET /credit-cards/count`` (HTTP 200)."""

    count: int = Field(description="Number of stored cards")


class ResetCreditCardsResponse(BaseModel):
    """Success response of ``POST /credit-cards/reset`` (HTTP 200).

    The message is the exact string of the API specification; it must not
    be translated.
    """

    msg: str = Field(description="Reset confirmation message")
