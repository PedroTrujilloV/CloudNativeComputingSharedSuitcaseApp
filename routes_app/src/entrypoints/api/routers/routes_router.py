import uuid
import re
from datetime import datetime, timezone

from fastapi import APIRouter, Query, Response, HTTPException
from fastapi.responses import JSONResponse

from adapters.database.connection import build_session_factory
from domain.models.route import Route, RouteCreateRequest, RouteCreateResponse
from domain.ports.route_repository_port import RouteRepositoryPort
from adapters.database.route_repository_adapter import SQLAlchemyRouteRepositoryAdapter


router = APIRouter(prefix="/routes")

UUID_PATTERN = re.compile(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$', re.IGNORECASE)


def get_repository() -> RouteRepositoryPort:
    """Dependency to get the route repository."""
    session_factory = build_session_factory()
    session = session_factory()
    try:
        return SQLAlchemyRouteRepositoryAdapter(session)
    finally:
        session.close()


def _validate_uuid_format(route_id: str) -> bool:
    """Validate that route_id is a valid UUID string.

    Returns:
        True if valid, False otherwise.
    """
    return bool(UUID_PATTERN.match(route_id))


@router.get("/ping", response_class=Response)
def ping():
    """Health check endpoint."""
    return Response(content="pong", media_type="text/plain")


@router.get("/count", status_code=200)
def count_routes():
    """Get the count of all routes in the database.

    Returns:
        JSON response with the count of routes.
    """
    repository = get_repository()
    count = repository.count()
    return {"count": count}


@router.get("/{route_id}", status_code=200)
def get_route_by_id(route_id: str):
    """Get a single route by its UUID.

    Args:
        route_id: UUID string identifying the route.

    Returns:
        Route object if found.

    Raises:
        HTTPException(400): If route_id is not a valid UUID format.
        HTTPException(404): If no route exists with the given id.
    """
    if not _validate_uuid_format(route_id):
        return JSONResponse(status_code=400, content={})

    repository = get_repository()
    route = repository.get_by_id(route_id)

    if not route:
        return JSONResponse(status_code=404, content={})

    return route.model_dump()


@router.post("", response_model=RouteCreateResponse, status_code=201)
def create_route(request: RouteCreateRequest):
    """Create a new route.

    Args:
        request: Route creation request with flight and journey details.

    Returns:
        Created route with id and createdAt timestamp.

    Raises:
        HTTPException(400): If any required field is missing.
        HTTPException(412): If flightId already exists or dates are invalid.
    """
    from domain.services.route_validation import validate_route_dates

    try:
        repository = get_repository()

        # Check for duplicate flightId
        existing = repository.get_by_flight_id(request.flightId)
        if existing:
            return JSONResponse(status_code=412, content={})

        # Validate route dates
        try:
            validate_route_dates(request.plannedStartDate, request.plannedEndDate)
        except ValueError:
            return JSONResponse(
                status_code=412,
                content={"msg": "Las fechas del trayecto no son válidas"},
            )

        # Create route
        route = Route(
            id=None,  # Will be generated by repository
            flightId=request.flightId,
            sourceAirportCode=request.sourceAirportCode,
            sourceCountry=request.sourceCountry,
            destinyAirportCode=request.destinyAirportCode,
            destinyCountry=request.destinyCountry,
            bagCost=request.bagCost,
            plannedStartDate=request.plannedStartDate,
            plannedEndDate=request.plannedEndDate,
            createdAt=None,
            updatedAt=None,
        )

        created_route = repository.create(route)

        return RouteCreateResponse(
            id=created_route.id,
            createdAt=created_route.createdAt
        )

    except Exception as e:
        raise HTTPException(
            status_code=400,
            detail=str(e)
        )


@router.get("", status_code=200)
def get_routes(flight: str | None = Query(None)):
    """Get all routes or filter by flightId.

    Args:
        flight: Optional flightId to filter routes by.

    Returns:
        List of routes matching the filter (or all routes if no filter).
        Returns an empty list [] if the filter matches nothing (HTTP 200).
    """
    try:
        repository = get_repository()
        if flight:
            routes = repository.list_routes(flight_id=flight)
            return [route.model_dump() for route in routes] if routes else []
        routes = repository.list_routes()
        return [route.model_dump() for route in routes]
    except Exception as e:
        raise HTTPException(status_code=400, detail=str(e))


@router.delete("/{route_id}")
def delete_route(route_id: str):
    """Delete a route by its UUID.

    Args:
        route_id: UUID string identifying the route.

    Returns:
        Success message if deletion is successful.

    Raises:
        HTTPException(400): If route_id is not a valid UUID format.
        HTTPException(404): If no route exists with the given id.
    """
    if not _validate_uuid_format(route_id):
        return JSONResponse(status_code=400, content={})

    repository = get_repository()
    route = repository.get_by_id(route_id)

    if not route:
        return JSONResponse(status_code=404, content={})

    repository.delete(route)
    return JSONResponse(status_code=200, content={"msg": "el trayecto fue eliminado"})


@router.post("/reset", status_code=200)
def reset_all_routes():
    """Delete all routes from the database.

    Returns:
        Success message confirming all data was deleted.
    """
    repository = get_repository()
    repository.delete_all()
    return JSONResponse(status_code=200, content={"msg": "Todos los datos fueron eliminados"})
